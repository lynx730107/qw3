"""Private IQ3_S integer shape constants; original scalar arithmetic and buffers."""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parent.parent
out = root / 'tests/.iq3_shape'
out.mkdir(exist_ok=True)
source = (root / 'metal/qw3_core_moe.metal').read_text()
name = 'qw3_matvec_iq3_s_fast'
first = source.index('kernel void ' + name + '(')
original = source[first:source.index('\n}\n', first)+3]
shader = '''constant uint private_iq3_shape_nb32 [[function_constant(902)]];
constant uint private_iq3_shape_stride [[function_constant(903)]];
'''
for variant in (1, 2):
    private = f'private_iq3_shape_fast{variant}'
    body = original.replace(name, private)
    old = 'uint nb32 = (args.n_in / 256u) * 8u;'
    assert body.count(old) == 1
    body = body.replace(old, 'uint nb32 = private_iq3_shape_nb32;')
    if variant == 2:
        body = body.replace('args.row_bytes', 'private_iq3_shape_stride')
    assert body.replace(private, name).replace('private_iq3_shape_nb32',
        '(args.n_in / 256u) * 8u').replace('private_iq3_shape_stride', 'args.row_bytes') == original
    shader += body
(out / 'kernels.metal').write_text(shader)

def rename(s):
    return (s.replace('iq3_input', 'iq3_shape').replace('IQ3Input', 'IQ3Shape')
            .replace('iq3Input', 'iq3Shape').replace('input_variant', 'shape_variant')
            .replace('IQ3 input', 'IQ3 shape').replace('IQ3_INPUT', 'IQ3_SHAPE')
            .replace('baseline/packed-input/packed-input-unroll2', 'baseline/K-constant/K-and-stride-constants'))

# Use the committed input-test snapshot, so a clean checkout does not need
# ignored files generated by a chain of previous experiments.
previous = root / 'docs/measurements/iq3_input_2026-10-12'
manifest = json.loads((previous / 'manifest.json').read_text())
def read_base(filename):
    name = 'tests/.iq3_input/' + filename
    path = previous / manifest['source_snapshot_paths'][name]
    content = path.read_bytes()
    assert hashlib.sha256(content).hexdigest() == manifest['source_sha256'][name], name
    return content.decode()

hooks = rename(read_base('hooks.inc'))
hooks = hooks.replace('Packed input loads; native weights, grid, FP32 arithmetic and data buffers.',
                      'Integer shape constants; native weights, grid, FP32 arithmetic and data buffers.')
hooks = hooks.replace('iq3_shape_pipeline[3]', 'iq3_shape_pipeline[3][5]', 1)
hooks = hooks.replace('static int shape_variant=1;', '''static int shape_variant=1,iq3_shape_mode;
static uint64_t iq3_shape_fallbacks;
static const uint32_t iq3_shape_inputs[5]={256u,4352u,5120u,6144u,17408u};
static _Thread_local void *iq3_shape_encoder;
static _Thread_local int iq3_shape_seen;
''')
hooks = hooks.replace('@protocol QW3IQ3ShapeHooks\n', '@protocol QW3IQ3ShapeHooks\n- (void)iq3ShapeSetBytes:(const void *)bytes length:(NSUInteger)length atIndex:(NSUInteger)index;\n')
a = hooks.index('- (void)iq3ShapeSetPipeline:', hooks.index('@implementation'))
z = hooks.index('\n@end', a)
hooks = hooks[:a] + '''- (void)iq3ShapeSetPipeline:(id<MTLComputePipelineState>)pipeline {
    iq3_shape_encoder=(__bridge void *)self;
    iq3_shape_seen=iq3_shape_mode && pipeline==iq3_shape_pipeline[0][0];
    [(id<MTLComputeCommandEncoder>)self setComputePipelineState:pipeline];
}
- (void)iq3ShapeSetBytes:(const void *)bytes length:(NSUInteger)length atIndex:(NSUInteger)index {
    if (iq3_shape_seen && iq3_shape_encoder==(__bridge void *)self && index==0 && length==3u*sizeof(uint32_t)) {
        const uint32_t *a=bytes;int shape=-1;
        for (int i=0;i<5;i++) if (a[0]==iq3_shape_inputs[i] && a[2]==a[0]/256u*110u) shape=i;
        if (shape>=0) {
            [(id<MTLComputeCommandEncoder>)self setComputePipelineState:iq3_shape_pipeline[shape_variant][shape]];
            iq3_shape_calls++;
        } else iq3_shape_fallbacks++;
        iq3_shape_seen=0;
    }
    [(id<MTLComputeCommandEncoder>)self setBytes:bytes length:length atIndex:index];
}
''' + hooks[z:]
hooks = hooks.replace('#define setComputePipelineState iq3ShapeSetPipeline', '#define setBytes iq3ShapeSetBytes\n#define setComputePipelineState iq3ShapeSetPipeline')
hooks = hooks.replace('#undef setComputePipelineState', '#undef setBytes\n#undef setComputePipelineState')
a = hooks.index('static int iq3_shape_compile(void) {')
hooks = hooks[:a] + '''static int iq3_shape_compile(void) {
    if (iq3_shape_pipeline[2][4]) return 1;
    if (!qw3_metal_compile_kernels()) return 0;
    for (int i=0;i<5;i++) iq3_shape_pipeline[0][i]=g_matvec_iq3_s_pipeline;
    NSError *error=nil;MTLCompileOptions *options=[MTLCompileOptions new];
    if (g_metal4_tensor_api_enabled) options.preprocessorMacros=@{@"QW3_METAL_HAS_TENSOR":@"1"};
    NSString *extra=[NSString stringWithContentsOfFile:@"tests/.iq3_shape/kernels.metal" encoding:NSUTF8StringEncoding error:&error];
    NSString *original=qw3_metal_full_kernel_source();
    NSString *source=extra && original ? [original stringByAppendingString:extra] : nil;
    id<MTLLibrary> lib=source ? [g_device newLibraryWithSource:source options:options error:&error] : nil;
    for (int v=1;v<=2;v++) for (int i=0;i<5;i++) {
        uint32_t nb32=iq3_shape_inputs[i]/32u,stride=iq3_shape_inputs[i]/256u*110u;
        MTLFunctionConstantValues *constants=[MTLFunctionConstantValues new];
        [constants setConstantValue:&nb32 type:MTLDataTypeUInt atIndex:902];
        if (v==2) [constants setConstantValue:&stride type:MTLDataTypeUInt atIndex:903];
        NSString *name=[NSString stringWithFormat:@"private_iq3_shape_fast%d",v];
        id<MTLFunction> fn=lib ? [lib newFunctionWithName:name constantValues:constants error:&error] : nil;
        id<MTLComputePipelineState> p=fn ? [g_device newComputePipelineStateWithFunction:fn error:&error] : nil;
        if (!p || p.threadExecutionWidth!=32 || p.maxTotalThreadsPerThreadgroup<64 ||
            p.staticThreadgroupMemoryLength!=iq3_shape_pipeline[0][0].staticThreadgroupMemoryLength) {
            fprintf(stderr,"IQ3 shape compile variant=%d n_in=%u: %s\\n",v,iq3_shape_inputs[i],error.localizedDescription.UTF8String);return 0;
        }
        iq3_shape_pipeline[v][i]=p;
        fprintf(stderr,"iq3_shape_metadata variant=%d n_in=%u nb32=%u stride_constant=%u width=%lu max_threads=%lu static_threadgroup_bytes=%lu matrix_dynamic_threadgroup_bytes=256 native_dynamic_threadgroup_bytes=128 threads=64\\n",v,iq3_shape_inputs[i],nb32,v==2 ? stride : 0u,(unsigned long)p.threadExecutionWidth,(unsigned long)p.maxTotalThreadsPerThreadgroup,(unsigned long)p.staticThreadgroupMemoryLength);
    }
    return 1;
}
static __attribute__((unused)) void scratch_select(int mode) {
    iq3_shape_mode=mode!=0;iq3_shape_seen=0;iq3_shape_encoder=NULL;
}
'''
(out / 'hooks.inc').write_text(hooks)
for filename in ('matrix.inc', 'model.inc', 'native.inc'):
    text = rename(read_base(filename))
    if filename == 'matrix.inc':
        text = text.replace('{17408,5120}}', '{17408,5120},{6144,5120},{8192,33}}').replace('shape<6', 'shape<8')
        text = text.replace('[(id<QW3IQ3ShapeHooks>)enc iq3ShapeSetPipeline:iq3_shape_pipeline[v ? shape_variant : 0]];',
                            'scratch_select(v);\n                [(id<QW3IQ3ShapeHooks>)enc iq3ShapeSetPipeline:iq3_shape_pipeline[0][0]];')
        text = text.replace('[enc setBytes:&args length:sizeof(args) atIndex:0];',
                            '[(id<QW3IQ3ShapeHooks>)enc iq3ShapeSetBytes:&args length:sizeof(args) atIndex:0];')
        text = text.replace('MTLSizeMake((no+7u)/8u,1,1)', 'MTLSizeMake((no+7u)/8u+1u,1,1)')
        text = text.replace('iq3_shape_calls!=36u', 'iq3_shape_calls!=42u || iq3_shape_fallbacks!=6u')
    elif filename == 'model.inc':
        text = text.replace('iq3_shape_calls=0;', 'iq3_shape_calls=0;iq3_shape_fallbacks=0;')
        text = text.replace('iq3_shape_calls!=(phase ? 32u*73u : 0u)',
                            'iq3_shape_calls!=(phase ? 32u*73u : 0u) || iq3_shape_fallbacks')
    else:
        text = text.replace('(!shape_variant && iq3_shape_calls)', '(!shape_variant && iq3_shape_calls) || iq3_shape_fallbacks')
    (out / filename).write_text(text)
