#!/usr/bin/env python3
"""Regenerate the agent's Unicode non-word formatting categories."""
from pathlib import Path
import unicodedata


def main():
    ranges = []
    first = last = None
    for cp in range(0x110000):
        category = unicodedata.category(chr(cp))
        if category[0] not in 'PSZM' and category != 'Cf':
            continue
        if last is not None and cp == last + 1:
            last = cp
        else:
            if last is not None:
                ranges.append((first, last))
            first = last = cp
    if last is not None:
        ranges.append((first, last))
    lines = [
        '/* Generated by tools/generate_agent_unicode.py; Unicode ' + unicodedata.unidata_version + '.',
        ' * Categories P*, S*, Z*, M*, Cf: punctuation, symbols, separators,',
        ' * combining marks and format controls (including emoji joiners). */',
        '#ifndef QW3_AGENT_UNICODE_H', '#define QW3_AGENT_UNICODE_H',
        'static const uint32_t agent_unicode_format_ranges[][2] = {',
    ]
    lines += ['    {0x%Xu, 0x%Xu},' % pair for pair in ranges]
    lines += ['};', '#endif', '']
    output = Path(__file__).resolve().parent.parent / 'qw3_agent_unicode.h'
    output.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
